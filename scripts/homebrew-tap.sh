#!/usr/bin/env bash
# The Homebrew formulae of the engrams CLI. Two formulae in the tap
# cortexapps/homebrew-tap follow the two channels: `engrams` is the newest
# stable release, `engrams-nightly` the newest prerelease. Each formula
# points at the binaries of one GitHub release and carries their checksums.
#
#   scripts/homebrew-tap.sh render  <formula> <version> <SHA256SUMS>  # formula on stdout
#   scripts/homebrew-tap.sh publish <formula> <version>               # write it to the tap
#
# <formula> is engrams or engrams-nightly. `publish` reads SHA256SUMS from
# the GitHub release v<version>, renders the formula, and commits it to the
# tap through the GitHub contents API. It needs HOMEBREW_TAP_TOKEN, a token
# with write access to the contents of the tap repository. release.yml runs
# it for a stable release and nightly.yml for a prerelease; a person can run
# it again by hand when that step failed, because a second publish of the
# same formula changes nothing.
set -euo pipefail

REPO="${ENGRAMS_REPO:-cortexapps/engrams}"
TAP_REPO="${HOMEBREW_TAP_REPO:-cortexapps/homebrew-tap}"

usage() {
  echo "usage: $0 render <engrams|engrams-nightly> <version> <SHA256SUMS>" >&2
  echo "       $0 publish <engrams|engrams-nightly> <version>" >&2
  exit 2
}

sum_of() {
  # sum_of <SHA256SUMS> <asset>
  local sum
  sum="$(awk -v a="$2" '$2 == a { print $1 }' "$1")"
  if [[ ! "$sum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "error: $1 has no sha256 for $2" >&2
    exit 1
  fi
  echo "$sum"
}

render() {
  local formula="$1" version="$2" sums="$3"
  local class conflicts="" base="https://github.com/$REPO/releases/download/v$version"
  local x64 arm64 darwin
  case "$formula" in
    engrams)
      class=Engrams
      ;;
    engrams-nightly)
      class=EngramsNightly
      conflicts=$'\n  conflicts_with "engrams", because: "both install the engrams binary"\n'
      ;;
    *) usage ;;
  esac
  x64="$(sum_of "$sums" engrams-linux-x64)"
  arm64="$(sum_of "$sums" engrams-linux-arm64)"
  darwin="$(sum_of "$sums" engrams-darwin-arm64)"
  cat <<FORMULA
# Generated by scripts/homebrew-tap.sh in $REPO. Do not edit by hand.
class $class < Formula
  desc "CLI and terminal client for engrams sessions"
  homepage "https://github.com/$REPO"
  version "$version"
  license "AGPL-3.0-only"
$conflicts
  on_macos do
    on_arm do
      url "$base/engrams-darwin-arm64"
      sha256 "$darwin"
    end
  end

  on_linux do
    on_intel do
      url "$base/engrams-linux-x64"
      sha256 "$x64"
    end
    on_arm do
      url "$base/engrams-linux-arm64"
      sha256 "$arm64"
    end
  end

  def install
    bin.install Dir["engrams-*"].first => "engrams"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/engrams --version").strip
  end
end
FORMULA
}

publish() {
  local formula="$1" version="$2" tmp path content sha
  : "${HOMEBREW_TAP_TOKEN:?HOMEBREW_TAP_TOKEN is needed to write to $TAP_REPO}"
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  gh release download "v$version" --repo "$REPO" --pattern SHA256SUMS --dir "$tmp"
  render "$formula" "$version" "$tmp/SHA256SUMS" > "$tmp/formula.rb"
  path="Formula/$formula.rb"
  export GH_TOKEN="$HOMEBREW_TAP_TOKEN"
  # The sha of the file that is there now, if any. The contents API needs it
  # for an update and refuses an update of a file that changed under us.
  sha="$(gh api "repos/$TAP_REPO/contents/$path" --jq .sha 2>/dev/null || true)"
  if [[ -n "$sha" ]]; then
    gh api "repos/$TAP_REPO/contents/$path" --jq .content | tr -d '\n' | base64 -d > "$tmp/current.rb"
    if cmp -s "$tmp/current.rb" "$tmp/formula.rb"; then
      echo "$TAP_REPO: $path is at $version already"
      return 0
    fi
  fi
  content="$(base64 < "$tmp/formula.rb" | tr -d '\n')"
  gh api -X PUT "repos/$TAP_REPO/contents/$path" \
    -f message="$formula $version" \
    -f content="$content" \
    ${sha:+-f sha="$sha"} \
    --jq '.commit.html_url'
}

[[ $# -ge 1 ]] || usage
case "$1" in
  render)
    [[ $# -eq 4 ]] || usage
    render "$2" "$3" "$4"
    ;;
  publish)
    [[ $# -eq 3 ]] || usage
    publish "$2" "$3"
    ;;
  *) usage ;;
esac
